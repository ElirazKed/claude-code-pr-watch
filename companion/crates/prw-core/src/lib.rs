//! The pure kernel of `prw`: no I/O, no async, no terminal, no clock (a time is always an
//! argument).
//!
//! Everything here is a function of its arguments, so it is tested with properties
//! (proptest) and against the mod's own fixtures rather than by hand. The `prw` binary does
//! the I/O and calls in here for every decision.
//!
//! - [`protocol`]: the shared files under `~/.cache/pr-watch/` (`results.json`, session
//!   files, the lease), parsed at the boundary: a torn file is an error or nothing, never a
//!   panic, and an odd field is absent.
//! - [`gh`]: a PR as `results.json` stores it (the mod's `GhPr`); [`time`]: its timestamps.
//! - [`status`]: what a card says of it (ports of `hooks/pr.ts`: `derive`, checks, merging).
//! - [`review`]: reviewers and open threads (`hooks/review.ts`).
//! - [`order`]: which PR comes first (`hooks/band.ts`).
//! - [`layout`]: which arrangement of panes fits a terminal width; [`panes`]: where each
//!   pane goes in it.
//! - [`ui`]: the TUI's state and what each message does to it (`update`, Elm-style).
//! - Taking part in the poll: [`poll`] (the give-way rule, the lease, a round's merge into
//!   `results.json`), [`batch`] (the batched query and what GitHub said, `hooks/batch.ts`),
//!   [`accounts`] (which gh login asks), [`rate`] (each login's budget), [`entries`] (what a
//!   failed fetch and a round do to an entry, `hooks/cache.ts`) and [`search`] (a login's
//!   own open PRs, and the saved searches [`config`] reads from `config.toml`).
//! - Acting on a PR: [`act`] (what the action keys do to the screen), [`merge`] (what `m`
//!   runs and what GitHub's answer means), [`comment`] (`c`), and the hand-offs [`handoff`] picks between, whose prompts are ports of the mod's:
//!   [`fix`] (failing checks and their logs), [`resolve`] (conflicts) and [`address`] (open
//!   review threads).
//! - Watches from other agents: [`watch`] (`prw watch` and the MCP `watch` tool: one file per
//!   watch, announced as one session file per agent's session) and [`mcp`] (`prw mcp`'s
//!   JSON-RPC).
//! - [`version`]: which `prw` this is, and whether a newer one is out.
//!
//! `companion/fixtures/status.ts`, generated by the mod's tests, holds [`status`] and
//! [`review`] to the mod's cards word for word (`tests/fixtures.rs`).

