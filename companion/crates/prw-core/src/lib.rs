//! The pure kernel of `prw`: no I/O, no async, no terminal, no clock (a time is always an
//! argument).
//!
//! Everything here is a function of its arguments, so it is tested with properties
//! (proptest) and against the mod's own fixtures rather than by hand. The `prw` binary does
//! the I/O and calls in here for every decision.
//!
//! - [`protocol`]: the shared files under `~/.cache/pr-watch/` (`results.json`, session
//!   files, the lease), parsed at the boundary: a torn file is an error or nothing, never a
//!   panic, and an odd field is absent.
//! - [`gh`]: a PR as `results.json` stores it (the mod's `GhPr`); [`time`]: its timestamps.
//! - [`status`]: what a card says of it (ports of `hooks/pr.ts`: `derive`, checks, merging).
//! - [`review`]: reviewers and open threads (`hooks/review.ts`).
//! - [`order`]: which PR comes first (`hooks/band.ts`).
//! - [`layout`]: which arrangement of panes fits a terminal width.
//!
//! `companion/fixtures/status.ts`, generated by the mod's tests, holds [`status`] and
//! [`review`] to the mod's cards word for word (`tests/fixtures.rs`).

pub mod gh;
pub mod layout;
mod lenient;
pub mod order;
pub mod protocol;
pub mod review;
pub mod status;
pub mod time;

pub use layout::{Layout, layout};
pub use order::{Tracked, order};
pub use protocol::{
    Entry, Lease, ParseError, SessionFile, Shared, parse_lease, parse_session, parse_shared,
    urls_in,
};
pub use status::{Derived, derive};
